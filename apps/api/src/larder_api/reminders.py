"""Reminders by Web Push. The worker runs both every hour (larder_worker.main; inline mode too).

- Expiry (`send_due`): once a day at `reminder_hour` in each user's own time zone, every browser
  they turned reminders on in gets "Use soon: milk (today), chicken (tomorrow)" for pantry food
  that expires today or tomorrow. Nothing expiring, nothing sent.
- Weekly recap (`send_recaps`): Sundays at `recap_hour`, the week so far in one line ("15 of 21
  planned meals eaten, EUR 62.40 spent of EUR 70.00"), opening /recap. Users can turn it off;
  a week with nothing logged, bought or weighed sends nothing.

Sending goes through `pywebpush` with the server's VAPID keys (settings; generated by
`larder-vapid`, kept in .env). A push service answering 404/410 means the browser unsubscribed:
that subscription is deleted. Any other failure is logged and retried at the next day's hour.
"""

import asyncio
import base64
import json
import logging
from collections.abc import Awaitable, Callable, Sequence
from dataclasses import dataclass
from datetime import date, datetime, timedelta, tzinfo
from typing import Any, cast
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from sqlalchemy import delete, select
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker
from sqlalchemy.orm import joinedload

from larder_api.insights import weekly_recap
from larder_api.schemas import RecapOut
from larder_api.settings import Settings
from larder_core.regions import local_today
from larder_db.models import PantryItem, PushSubscription, User

__all__ = [
    "Gone",
    "Reminder",
    "generate_vapid_keys",
    "recap_reminder",
    "reminder_for",
    "send_due",
    "send_recaps",
]

logger = logging.getLogger(__name__)


class Gone(Exception):
    """The push service no longer knows this subscription (HTTP 404 or 410)."""


@dataclass(frozen=True, slots=True)
class Reminder:
    title: str
    body: str
    url: str = "/pantry"

    def payload(self) -> str:
        return json.dumps({"title": self.title, "body": self.body, "url": self.url})


type Sender = Callable[[PushSubscription, Reminder], Awaitable[None]]


def _short(description: str) -> str:
    return description.split(",", 1)[0].strip()


async def reminder_for(session: AsyncSession, user_id: int, today: date) -> Reminder | None:
    """What to say today: food expiring today or tomorrow, soonest first (None: nothing)."""
    rows = (
        await session.scalars(
            select(PantryItem)
            .where(
                PantryItem.user_id == user_id,
                PantryItem.grams > 0,
                PantryItem.expires_on >= today,
                PantryItem.expires_on <= today + timedelta(days=1),
            )
            .options(joinedload(PantryItem.food))
            .order_by(PantryItem.expires_on, PantryItem.id)
        )
    ).all()
    if not rows:
        return None
    names = [
        f"{_short(r.food.description).lower()} ({'today' if r.expires_on == today else 'tomorrow'})"
        for r in rows[:4]
    ]
    more = f" and {len(rows) - 4} more" if len(rows) > 4 else ""
    title = "Use soon" if len(rows) > 1 else "Use it soon"
    return Reminder(title, f"{', '.join(names)}{more}. Open your pantry for ideas.")


async def send_due(
    sessionmaker: async_sessionmaker[AsyncSession],
    now: datetime,
    settings: Settings,
    send: Sender | None = None,
) -> int:
    """Send today's reminders to users whose local time is `reminder_hour`; returns how many
    pushes went out."""
    if send is None:
        if not (settings.vapid_public_key and settings.vapid_private_key):
            return 0
        send = webpush_sender(settings)
    sent = 0
    async with sessionmaker() as session:
        subs = (
            await session.scalars(select(PushSubscription).order_by(PushSubscription.user_id))
        ).all()
        users = {
            u.id: u
            for u in await session.scalars(
                select(User).where(User.id.in_({s.user_id for s in subs}))
            )
        }
        gone: list[int] = []
        reminders: dict[int, Reminder | None] = {}
        for sub in subs:
            user = users.get(sub.user_id)
            if user is None:
                continue
            local = now.astimezone(_zone(user.timezone))
            today = local_today(user.timezone, now)
            if local.hour != settings.reminder_hour or sub.last_sent_on == today:
                continue
            if sub.user_id not in reminders:
                reminders[sub.user_id] = await reminder_for(session, sub.user_id, today)
            reminder = reminders[sub.user_id]
            sub.last_sent_on = today  # checked today, sent or not: once a day
            if reminder is None:
                continue
            try:
                await send(sub, reminder)
                sent += 1
            except Gone:
                gone.append(sub.id)
            except Exception:
                logger.exception("push to subscription %d failed", sub.id)
        if gone:
            await session.execute(delete(PushSubscription).where(PushSubscription.id.in_(gone)))
        await session.commit()
    return sent


SYMBOLS = {"GBP": "£", "EUR": "€", "USD": "$"}


def _money(minor: int, currency: str) -> str:
    return f"{SYMBOLS.get(currency, currency + ' ')}{minor / 100:,.2f}"


def recap_reminder(recap: RecapOut) -> Reminder | None:
    """The week in one line, or None for a week with nothing in it."""
    if recap.empty:
        return None
    parts: list[str] = []
    if recap.planned_meals:
        parts.append(f"{recap.eaten_meals} of {recap.planned_meals} planned meals eaten")
    elif recap.logged_days:
        parts.append(f"{recap.logged_days} {'day' if recap.logged_days == 1 else 'days'} logged")
    if recap.spent_minor:
        spent = _money(recap.spent_minor, recap.currency)
        budget = recap.budget_minor
        parts.append(
            f"{spent} spent of {_money(budget, recap.currency)}" if budget else f"{spent} spent"
        )
    if recap.weight_change_kg:
        parts.append(f"weight {recap.weight_change_kg:+.1f} kg")
    body = ", ".join(parts) if parts else "Your week is in"
    return Reminder(
        "Your week in review",
        f"{body[0].upper()}{body[1:]}. Tap to see it.",
        url=f"/recap?week={recap.week_start.isoformat()}",
    )


async def send_recaps(
    sessionmaker: async_sessionmaker[AsyncSession],
    now: datetime,
    settings: Settings,
    send: Sender | None = None,
) -> int:
    """Send the weekly recap to users whose local time is Sunday at `recap_hour`; returns how
    many pushes went out. Once per browser per Sunday."""
    if send is None:
        if not (settings.vapid_public_key and settings.vapid_private_key):
            return 0
        send = webpush_sender(settings)
    sent = 0
    async with sessionmaker() as session:
        subs = (
            await session.scalars(select(PushSubscription).order_by(PushSubscription.user_id))
        ).all()
        users = {
            u.id: u
            for u in await session.scalars(
                select(User).where(User.id.in_({s.user_id for s in subs}))
            )
        }
        gone: list[int] = []
        recaps: dict[int, Reminder | None] = {}
        for sub in subs:
            user = users.get(sub.user_id)
            if user is None or not user.weekly_recap:
                continue
            local = now.astimezone(_zone(user.timezone))
            today = local_today(user.timezone, now)
            if (
                local.weekday() != 6
                or local.hour != settings.recap_hour
                or sub.recap_sent_on == today
            ):
                continue
            if user.id not in recaps:
                week = today - timedelta(days=6)
                recaps[user.id] = recap_reminder(await weekly_recap(session, user, week, today))
            reminder = recaps[user.id]
            sub.recap_sent_on = today
            if reminder is None:
                continue
            try:
                await send(sub, reminder)
                sent += 1
            except Gone:
                gone.append(sub.id)
            except Exception:
                logger.exception("recap push to subscription %d failed", sub.id)
        if gone:
            await session.execute(delete(PushSubscription).where(PushSubscription.id.in_(gone)))
        await session.commit()
    return sent


def _zone(name: str | None) -> tzinfo:
    try:
        return ZoneInfo(name or "UTC")
    except (ZoneInfoNotFoundError, ValueError):
        return ZoneInfo("UTC")


def webpush_sender(settings: Settings) -> Sender:
    import pywebpush  # pyright: ignore[reportMissingTypeStubs]

    webpush = cast(Callable[..., object], pywebpush.webpush)  # pyright: ignore[reportUnknownMemberType]
    push_error = cast(type[Exception], pywebpush.WebPushException)
    assert settings.vapid_private_key is not None
    private = settings.vapid_private_key.get_secret_value()

    def push(sub: PushSubscription, reminder: Reminder) -> None:
        try:
            webpush(
                {"endpoint": sub.endpoint, "keys": {"p256dh": sub.p256dh, "auth": sub.auth}},
                data=reminder.payload(),
                vapid_private_key=private,
                vapid_claims={"sub": settings.vapid_subject},
                ttl=12 * 3600,
                timeout=10,
            )
        except push_error as e:
            status = getattr(cast(Any, e).response, "status_code", None)
            if status in (404, 410):
                raise Gone from e
            raise

    async def send(sub: PushSubscription, reminder: Reminder) -> None:
        await asyncio.to_thread(push, sub, reminder)

    return send


def _b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def generate_vapid_keys() -> tuple[str, str]:
    """A new (public, private) VAPID key pair, base64url: the public key as the uncompressed
    P-256 point browsers take as `applicationServerKey`, the private key as the raw scalar."""
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

    key = ec.generate_private_key(ec.SECP256R1())
    public = key.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
    private = key.private_numbers().private_value.to_bytes(32, "big")
    return _b64(public), _b64(private)


def vapid_main(argv: Sequence[str] | None = None) -> None:
    """`larder-vapid`: print a key pair to paste into .env (never commit it)."""
    public, private = generate_vapid_keys()
    print(f"VAPID_PUBLIC_KEY={public}")
    print(f"VAPID_PRIVATE_KEY={private}")
